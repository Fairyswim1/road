import assert from 'node:assert/strict';
import {mkdirSync,writeFileSync} from 'node:fs';
const base='http://127.0.0.1:5173';
async function call(body,token){const r=await fetch(base+'/api/game',{method:'POST',headers:{'Content-Type':'application/json',...(token?{Authorization:'Bearer '+token}:{})},body:JSON.stringify(body)});return {status:r.status,data:await r.json()};}
const created=await call({action:'create',title:'기능 확인용 수업',names:['탐험 1모둠','탐험 2모둠','탐험 3모둠','탐험 4모둠','탐험 5모둠'],pin:'246810',cardCount:150,searchMinutes:20,solveMinutes:10,allNumbers:false});
assert.equal(created.status,200,JSON.stringify(created.data));const {id,adminToken,game}=created.data;
const t1=game.teams[0],t2=game.teams[1];
const request=(action,extra={},token=adminToken)=>call({action,id,...extra},token);
assert.equal((await request('claim',{code:game.cards[0].secret},t1.token)).status,409);
assert.equal((await request('start',{},t1.token)).status,403);
assert.equal((await request('start')).status,200);
const race=await Promise.all([request('claim',{code:game.cards[0].secret},t1.token),request('claim',{code:game.cards[0].secret},t2.token)]);
assert.deepEqual(race.map(x=>x.status).sort(),[200,409]);
for(let i=1;i<16;i++)assert.equal((await request('claim',{code:game.cards[i].secret},game.teams[(i-1)%5].token)).status,200);
const own=await fetch(base+'/api/game?id='+id,{headers:{Authorization:'Bearer '+t1.token}}).then(r=>r.json());
assert.equal(own.game.teams.length,1);assert.ok(own.game.cards.every(c=>c.owner===t1.id&&!c.secret));assert.ok(!own.game.teams[0].token);
const unauth=await fetch(base+'/api/game?id='+id);assert.equal(unauth.status,403);
assert.equal((await request('return',{teamId:t1.id})).status,200);
assert.equal((await request('claim',{code:game.cards[20].secret},t1.token)).status,409);
assert.equal((await request('solve',{teamId:t1.id})).status,200);
const board=Array(36).fill(null);board[0]=own.game.cards[0].id;
assert.equal((await request('board',{teamId:t1.id,board,boardVersion:0})).status,200);
assert.equal((await request('board',{teamId:t1.id,board,boardVersion:0})).status,409);
const badBoard=[...board];badBoard[1]=game.cards[20].id;
assert.equal((await request('board',{teamId:t1.id,board:badBoard,boardVersion:1})).status,400);
assert.equal((await request('unlock',{pin:'000000'})).status,403);
assert.equal((await request('unlock',{pin:'246810'})).status,200);
assert.equal((await request('pause',{teamId:t1.id})).status,200);
assert.equal((await request('board',{teamId:t1.id,board,boardVersion:1})).status,409);
mkdirSync('.sites-runtime',{recursive:true});writeFileSync('.sites-runtime/test-session.json',JSON.stringify({id,adminToken,teamToken:t1.token,pin:'246810'}));
console.log('PASS: 5 teams, exclusive concurrent claim, authorization, filtered inventories, early return, board persistence/version checks, PIN and pause');
console.log('Local QA admin: '+base+'/#g='+id+'&a='+adminToken);
console.log('Local QA student: '+base+'/#g='+id+'&t='+t1.token);
